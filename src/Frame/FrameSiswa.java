    private void tblSiswaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSiswaMouseClicked
        // TODO add your handling code here:
        int baris = tblSiswa.getSelectedRow();
        String Nama = tblSiswa.getValueAt(baris, 0).toString();
        String Nis = tblSiswa.getValueAt(baris, 1).toString();
        String Alamat = tblSiswa.getValueAt(baris, 2).toString();
        String Kelas = tblSiswa.getValueAt(baris, 3).toString();
        txtNama.setText(Nama);
        txtNis.setText(Nis);
        txtAlamat.setText(Alamat);
        cmbKelas.setSelectedItem(Kelas);
    }//GEN-LAST:event_tblSiswaMouseClicked

