    public void tampilDataSiswa(){
        DefaultTableModel SiswaModel = new DefaultTableModel();
        SiswaModel.addColumn("Nama");
        SiswaModel.addColumn("Nis");
        SiswaModel.addColumn("Alamat");
        SiswaModel.addColumn("Kelas");
        
        for (int i = 0; i < employee.listDatanama_siswa().size(); i++){
            String Nama = employee.listDatanama_siswa().get(i);
            String Nis = employee.listDatanis().get(i);
            String Alamat = employee.listDataalamat_siswa().get(i);
            String Kelas = employee.listDataId_kelas().get(i).toString();
            
            Object[] barisData = {Nama, Nis, Alamat, Kelas};
            SiswaModel.addRow(barisData);
        }
        tblSiswa.setModel(SiswaModel);
    }

