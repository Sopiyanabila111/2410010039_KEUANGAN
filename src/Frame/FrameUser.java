public void tampilDataUser() {
    DefaultTableModel userModel = new DefaultTableModel();
    userModel.addColumn("Nama");
    userModel.addColumn("Jenis Kelamin");
    userModel.addColumn("Email");
    userModel.addColumn("IdUser");

    for (int i = 0; i < employee.listDataNamaUser().size(); i++) {
        String namaUser      = employee.listDataNamaUser().get(i);
        String jenisKelamin  = employee.listDataJenisKelamin().get(i);
        String emailUser     = employee.listDataemailUser().get(i);
        String idUser        = employee.listDataidUser().get(i).toString();

        Object[] barisData = {namaUser, jenisKelamin, emailUser, idUser};
        userModel.addRow(barisData);
    }

    tblUser.setModel(userModel);
}

