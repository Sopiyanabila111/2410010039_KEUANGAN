    private void tblUserMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUserMouseClicked
        // TODO add your handling code here:
        int baris = tblUser.getSelectedRow();
        String NamaUser = tblUser.getValueAt(baris, 0).toString();
        String JenisKelamin = tblUser.getValueAt(baris, 1).toString();
        String emailUser = tblUser.getValueAt(baris, 2).toString();
        String IdUser = tblUser.getValueAt(baris, 3).toString();
        txtNamaUser.setText(NamaUser);
        cmbJenisKelamin.setSelectedItem(JenisKelamin);
        txtemailUser.setText(emailUser);
        txtIdUser.setText(IdUser);
    }//GEN-LAST:event_tblUserMouseClicked

